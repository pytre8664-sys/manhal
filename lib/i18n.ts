export const DICT: Record<Lang, I18nDict> = {
  ar: { ...I18N.ar, ...EXTRA.ar },
  en: { ...I18N.en, ...EXTRA.en },
};

export function translate(lang: Lang, key: string): string {
  return DICT[lang]?.[key] ?? DICT.ar[key] ?? key;
}

export function localize(lang: Lang, obj?: { ar: string; en: string } | null): string {
  if (!obj) return "";
  return lang === "en" ? obj.en || obj.ar : obj.ar || obj.en;
}
